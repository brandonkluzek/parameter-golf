from __future__ import annotations

import json
import shutil
from datetime import datetime, timezone
from pathlib import Path

from . import REPO_ROOT
from .manifest import resolve_manifest


def _slug(text: str) -> str:
    return "".join(ch.lower() if ch.isalnum() else "_" for ch in text).strip("_")


def promote_run(run_dir: Path, *, destination: Path | None = None) -> Path:
    summary = json.loads((run_dir / "summary.json").read_text(encoding="utf-8"))
    manifest = resolve_manifest(run_dir / "manifest.resolved.toml")
    candidate = manifest.promotion.candidate
    track = manifest.promotion.track_override or manifest.track
    if track == "record":
        track_dir = REPO_ROOT / "records" / "track_10min_16mb"
    else:
        track_dir = REPO_ROOT / "records" / "track_non_record_16mb"
    date_str = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    slug = _slug(manifest.promotion.name or manifest.variant_name)
    target_dir = destination or (track_dir / f"{date_str}_{slug}")
    if target_dir.exists():
        raise FileExistsError(f"Promotion target already exists: {target_dir}")
    target_dir.mkdir(parents=True, exist_ok=False)

    source_script = run_dir / "source" / Path(manifest.script_path).name
    if source_script.exists():
        shutil.copy2(source_script, target_dir / "train_gpt.py")
    if (run_dir / "train.log").exists():
        shutil.copy2(run_dir / "train.log", target_dir / "train.log")
    if (run_dir / "stdout.log").exists():
        shutil.copy2(run_dir / "stdout.log", target_dir / "stdout.log")
    if (run_dir / "manifest.resolved.toml").exists():
        shutil.copy2(run_dir / "manifest.resolved.toml", target_dir / "manifest.resolved.toml")
    if (run_dir / "summary.json").exists():
        shutil.copy2(run_dir / "summary.json", target_dir / "summary.json")
    if (run_dir / "final_model.pt").exists():
        shutil.copy2(run_dir / "final_model.pt", target_dir / "final_model.pt")
    if (run_dir / "final_model.int8.ptz").exists():
        shutil.copy2(run_dir / "final_model.int8.ptz", target_dir / "final_model.int8.ptz")
    if (run_dir / "final_model.export.ptz").exists():
        shutil.copy2(run_dir / "final_model.export.ptz", target_dir / "final_model.export.ptz")

    submission = {
        "author": manifest.promotion.name or "TODO",
        "github_id": "TODO",
        "name": manifest.promotion.name or manifest.variant_name,
        "blurb": manifest.promotion.blurb or f"Promoted from experiment run {summary.get('run_id', run_dir.name)}.",
        "date": summary.get("end_time_iso", datetime.now(timezone.utc).strftime("%Y-%m-%d"))[:10],
        "val_loss": summary.get("metrics", {}).get("final_roundtrip_val_loss"),
        "val_bpb": summary.get("metrics", {}).get("final_roundtrip_val_bpb"),
        "bytes_total": summary.get("artifacts", {}).get("export_total_bytes"),
    }
    (target_dir / "submission.json").write_text(json.dumps(submission, indent=2) + "\n", encoding="utf-8")

    readme = f"""# {manifest.promotion.name or manifest.variant_name}

Status: draft promotion from local experiment ops

Candidate class: `{candidate}`

## Model summary

- Baseline: `{manifest.baseline}`
- Script: `{Path(manifest.script_path).name}`
- Resource class: `{manifest.resource_class}`
- Seed mode: `{manifest.seed_mode}`

## Training setup

- Run ID: `{summary.get("run_id", run_dir.name)}`
- Git SHA: `{summary.get("git_sha", "")}`
- Final eval mode: `{summary.get("trainer", {}).get("final_eval_mode", "standard")}`
- Final eval stride: `{summary.get("trainer", {}).get("final_eval_stride", "")}`

## Key metrics

- Final roundtrip `val_loss`: `{summary.get("metrics", {}).get("final_roundtrip_val_loss")}`
- Final roundtrip `val_bpb`: `{summary.get("metrics", {}).get("final_roundtrip_val_bpb")}`
- Final eval time (ms): `{summary.get("metrics", {}).get("final_eval_time_ms")}`

## Artifact bytes

- Raw model bytes: `{summary.get("artifacts", {}).get("raw_model_bytes")}`
- Export model bytes: `{summary.get("artifacts", {}).get("export_model_bytes")}`
- Total bytes: `{summary.get("artifacts", {}).get("export_total_bytes")}`
- Code bytes: `{summary.get("artifacts", {}).get("code_bytes")}`

## Reproducibility notes

- This folder was generated by `python -m tools.experiments promote`.
- Replace placeholder author / GitHub metadata before any PR.
- Validate leaderboard eligibility separately; promotion does not claim it.

## Included files

- `train_gpt.py`
- `train.log`
- `stdout.log` (if collected)
- `summary.json`
- `submission.json`
- `manifest.resolved.toml`
- `final_model.pt` / export artifact (if collected)
"""
    (target_dir / "README.md").write_text(readme, encoding="utf-8")
    return target_dir
